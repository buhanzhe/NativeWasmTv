const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const file = path.resolve(__dirname, '../app/src/main/assets/control/js/pages/channels.js');
const context = vm.createContext({ window: { addEventListener() {} }, startPage() {}, URL });
vm.runInContext(fs.readFileSync(file, 'utf8'), context);
assert.equal(context.playlistAddressProblem('tvbus://38TRb4vQYyBPj58zv1KcJv99R91XqmVfsdVpqmKkTZHoW8xd1k', false), '');
assert.notEqual(context.playlistAddressProblem('tvbus://abc', true), '');
assert.equal(context.playlistStreamUrl('tvbus://AbCd123', 'https://example.com/list.txt'), 'tvbus://AbCd123');
const text = 'Test,#genre#\nOne,tvbus://AbCd123\nTwo,tvbus://EfGh456\n';
const parsed = context.parsePlaylistOnPhone(text, { id: 'test', name: 'test', location: 'https://example.com/list.txt' });
assert.equal(parsed.entries.length, 2);
assert.equal(parsed.entries[0].url, 'tvbus://AbCd123');
assert.equal(parsed.entries[1].url, 'tvbus://EfGh456');
assert.equal(context.playlistAddressProblem('sop://broker.example:80/20040', false), '');
assert.equal(context.playlistStreamUrl('sop://broker.example:80/20040', 'https://example.com/list.txt'), 'sop://broker.example:80/20040');
assert.equal(context.parsePlaylistOnPhone('SOP,sop://broker.example:80/20040\n', {id:'sop', name:'sop',location:'https://example.com/list.txt'}).entries[0].url, 'sop://broker.example:80/20040');
console.log('PASS TVBus web import: scheme validation, source restrictions, case preservation and TXT parsing');
